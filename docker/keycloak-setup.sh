#!/usr/bin/env bash
#
# Runs once Keycloak is healthy (docker compose service keycloak-setup):
# reads the client secrets Keycloak generated when it imported the
# trust-sample realm and writes them where the samples read them,
# env/trust-sample-client-secrets.env. Safe to run again: the secrets of an
# existing realm do not change.
set -euo pipefail

KCADM="/opt/keycloak/bin/kcadm.sh"
CONFIG=/tmp/kcadm.config
REALM=trust-sample
OUT=/out/trust-sample-client-secrets.env

kcadm() { "$KCADM" "$@" --config "$CONFIG"; }

"$KCADM" config credentials --config "$CONFIG" --server "$KEYCLOAK_URL" --realm master \
  --user "$KEYCLOAK_ADMIN" --password "$KEYCLOAK_ADMIN_PASSWORD" >/dev/null

TMP="$(mktemp)"
{
  echo "# Generated by keycloak-setup from the '$REALM' realm. Do not commit."
  for client in trust-sample-api trust-sample-bff trust-sample-downstream-api; do
    id="$(kcadm get clients -r "$REALM" -q clientId="$client" --fields id --format csv --noquotes)"
    [ -n "$id" ] || { echo "ERROR: client $client not found in realm $REALM" >&2; exit 1; }
    secret="$(kcadm get "clients/$id/client-secret" -r "$REALM" --fields value --format csv --noquotes)"
    if [ -z "$secret" ]; then
      kcadm create "clients/$id/client-secret" -r "$REALM" >/dev/null
      secret="$(kcadm get "clients/$id/client-secret" -r "$REALM" --fields value --format csv --noquotes)"
    fi
    name="${client#trust-sample-}"
    name="${name//-/_}"
    echo "TRUST_SAMPLE_${name^^}_CLIENT_SECRET=$secret"
  done
} > "$TMP"

mv "$TMP" "$OUT"
chmod 644 "$OUT"
echo "[OK] client secrets of realm '$REALM' written to env/$(basename "$OUT")"
